#!/usr/bin/env node
/**
 * Generates the inputs for the Luau test run.
 *
 * The standalone `luau` CLI has no filesystem access, so both the compiled
 * package sources and the test fixtures have to be handed to it as Luau
 * literals. This writes two generated modules:
 *
 * - `sources.luau`   — every `.luau` file `rbxtsc` emitted, verbatim, for
 *                      `@rbxts/svg` and both framework bindings.
 * - `fixtures.luau`  — real SVGs compiled by the real Rust compiler, as base64,
 *                      alongside the values the Luau side should decode.
 * - `vide-sources.luau` — the installed `@rbxts/vide`'s own Luau source.
 *
 * That second file is what makes the Luau suite worth running: it exercises the
 * decoder against genuine compiler output rather than against bytes written by
 * hand to match the decoder's expectations. The third does the same for the
 * Vide binding's lifecycle tests: they run the real reactive library — real
 * scopes, real cleanup ordering, real strict mode — rather than a hand-written
 * stand-in that would agree with whatever the binding happened to do.
 */

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(here, "../..");
// `@rbxts/svg-vide` is bundled alongside the core because Vide, unlike React,
// is a pure Luau library with no engine dependency beyond instance creation —
// so the binding's real compiled output can be executed here, against the real
// reactive library, with only Roblox datatypes and instances mocked.
const outDirs = [
	join(repoRoot, "packages/svg/out"),
	join(repoRoot, "packages/svg-vide/out"),
];
const fixturesDir = join(repoRoot, "tests/fixtures");
// pnpm links workspace dependencies, so the binding's own `node_modules` is
// the installed copy the binding compiles against — the version under test.
const videSrcDir = join(repoRoot, "packages/svg-vide/node_modules/@rbxts/vide/src");

const { compileSvgFile, renderSvgIr } = await import(
	join(repoRoot, "packages/compiler/dist/index.js")
);

/**
 * Escapes bytes into a Lua double-quoted string.
 *
 * Long-bracket syntax would be prettier but is unsafe for arbitrary content,
 * and the sources contain box-drawing characters in comments. Byte-wise decimal
 * escaping is exact for any input.
 */
function luaString(text) {
	const bytes = Buffer.from(text, "utf8");
	let out = '"';
	for (const byte of bytes) {
		if (byte === 0x22) out += '\\"';
		else if (byte === 0x5c) out += "\\\\";
		else if (byte === 0x0a) out += "\\n";
		else if (byte === 0x0d) out += "\\r";
		else if (byte === 0x09) out += "\\t";
		else if (byte >= 0x20 && byte <= 0x7e) out += String.fromCharCode(byte);
		else out += `\\${byte.toString().padStart(3, "0")}`;
	}
	return out + '"';
}

function findLuau(dir) {
	const found = [];
	for (const entry of readdirSync(dir, { withFileTypes: true })) {
		const path = join(dir, entry.name);
		if (entry.isDirectory()) found.push(...findLuau(path));
		else if (entry.name.endsWith(".luau")) found.push(path);
	}
	return found.sort();
}

// ---- sources.luau ----------------------------------------------------------
// Keys are paths relative to the repo root without the `.luau` extension, which
// is the module-path form the harness resolves against.
const sourceFiles = outDirs.flatMap(findLuau);
const sourceLines = ["--!nocheck", "-- Generated by bundle.mjs. Do not edit.", "return {"];
for (const path of sourceFiles) {
	const key = relative(repoRoot, path).replace(/\.luau$/, "");
	sourceLines.push(`\t[${luaString(key)}] = ${luaString(readFileSync(path, "utf8"))},`);
}
sourceLines.push("}", "");
writeFileSync(join(here, "sources.luau"), sourceLines.join("\n"));

// ---- vide-sources.luau -----------------------------------------------------
// Vide's own modules require each other with plain relative string requires
// (`require "./graph"`), which the standalone CLI resolves against a real file
// path — and these are loaded through the same `loadstring` harness as
// everything else, which has no real path. So they are embedded by module name
// and handed a `require` of their own. Keys are the bare module names, which is
// all `./x` and `../test/mock` ever reduce to.
const videFiles = readdirSync(videSrcDir)
	.filter((name) => name.endsWith(".luau"))
	.sort();
const videLines = ["--!nocheck", "-- Generated by bundle.mjs from @rbxts/vide. Do not edit.", "return {"];
for (const name of videFiles) {
	videLines.push(
		`\t[${luaString(name.replace(/\.luau$/, ""))}] = ${luaString(
			readFileSync(join(videSrcDir, name), "utf8"),
		)},`,
	);
}
videLines.push("}", "");
writeFileSync(join(here, "vide-sources.luau"), videLines.join("\n"));

const videVersion = JSON.parse(
	readFileSync(join(videSrcDir, "../package.json"), "utf8"),
).version;

// ---- fixtures.luau ---------------------------------------------------------
const FIXTURES = [
	["lucideSearch", "lucide/search.svg"],
	["lucideSettings", "lucide/settings.svg"],
	["lucideCircleAlert", "lucide/circle-alert.svg"],
	["lucideChevronDown", "lucide/chevron-down.svg"],
	["lucideGitBranch", "lucide/git-branch.svg"],
	["lucideBell", "lucide/bell.svg"],
	["evenOdd", "basic/evenodd.svg"],
	["multipleSubpaths", "basic/multiple-subpaths.svg"],
	["offsetViewBox", "basic/offset-viewbox.svg"],
	["solidFill", "basic/simple-path.svg"],
	["strokeRound", "basic/stroke-round.svg"],
	["mixedCurrentColor", "basic/mixed-current-color.svg"],
	// The three differ only in `preserveAspectRatio`, so they are what proves
	// the policy actually reaches the Luau decoder rather than being defaulted.
	["aspectMeet", "basic/aspect-meet.svg"],
	["aspectNone", "basic/aspect-none.svg"],
	["aspectSlice", "basic/aspect-slice.svg"],
];

const fixtureLines = [
	"--!nocheck",
	"-- Generated by bundle.mjs from tests/fixtures via the real compiler.",
	"return {",
	"\tassets = {",
];
for (const [name, relativePath] of FIXTURES) {
	const compiled = compileSvgFile(join(fixturesDir, relativePath));
	fixtureLines.push(
		`\t\t${name} = {`,
		`\t\t\tsource = ${luaString(relativePath)},`,
		`\t\t\tbase64 = ${luaString(compiled.data.toString("base64"))},`,
		`\t\t\thash = ${luaString(compiled.hash)},`,
		`\t\t\tbyteLength = ${compiled.data.length},`,
		`\t\t\tirVersion = ${compiled.irVersion},`,
		`\t\t\tflags = ${compiled.flags},`,
		`\t\t\tshapeCount = ${compiled.shapeCount},`,
		`\t\t\tviewBox = { x = ${compiled.viewBox.x}, y = ${compiled.viewBox.y}, ` +
			`width = ${compiled.viewBox.width}, height = ${compiled.viewBox.height} },`,
		`\t\t\tpreserveAspectRatio = ${luaString(compiled.preserveAspectRatio)},`,
		"\t\t},",
	);
}
fixtureLines.push("\t},");
// Deliberately corrupted variants, so the decoder's rejection paths are tested
// against real headers rather than against arbitrary bytes that would fail for
// the wrong reason.
const search = compileSvgFile(join(fixturesDir, "lucide/search.svg"));

const wrongVersion = Buffer.from(search.data);
wrongVersion.writeUInt16LE(search.irVersion + 1, 4);

const wrongMagic = Buffer.from(search.data);
wrongMagic[0] = 0x58; // "X"

// Header claims more shapes than the blob can hold.
const overlongTables = Buffer.from(search.data);
overlongTables.writeUInt16LE(4096, 30);

fixtureLines.push(
	"\tcorrupt = {",
	`\t\twrongVersion = ${luaString(wrongVersion.toString("base64"))},`,
	`\t\twrongMagic = ${luaString(wrongMagic.toString("base64"))},`,
	`\t\toverlongTables = ${luaString(overlongTables.toString("base64"))},`,
	`\t\theaderOnly = ${luaString(search.data.subarray(0, 16).toString("base64"))},`,
	"\t},",
);

fixtureLines.push("}", "");
writeFileSync(join(here, "fixtures.luau"), fixtureLines.join("\n"));

// ---- goldens.luau ----------------------------------------------------------
// Reference raster output for a matrix of fixtures, sizes and options,
// produced by the *Rust* renderer through the native binding. The Luau
// rasterizer renders the same asset with the same options and is compared
// against these bytes — which is the cross-language check the whole
// reference-renderer design exists for. Regenerated on every test run, so the
// goldens can never drift from the Rust implementation.
const GOLDENS = [
	// The Lucide fast path: tintable alpha masks across the size ladder.
	["lucideSearch", 16, 16, { alphaMask: true }],
	["lucideSearch", 24, 24, { alphaMask: true }],
	["lucideSearch", 32, 32, { alphaMask: true }],
	["lucideSearch", 64, 64, { alphaMask: true }],
	["lucideSettings", 24, 24, { alphaMask: true }],
	["lucideChevronDown", 24, 24, { alphaMask: true }],
	["lucideGitBranch", 24, 24, { alphaMask: true }],
	["lucideCircleAlert", 24, 24, { alphaMask: true }],
	["lucideBell", 24, 24, { alphaMask: true }],
	// Stroke overrides, relative and absolute.
	["lucideSearch", 24, 24, { alphaMask: true, strokeWidth: 1 }],
	["lucideSearch", 48, 48, { alphaMask: true, strokeWidth: 2, absoluteStrokeWidth: true }],
	// Full colour: fixed paints, fill rules, currentColor resolution.
	["solidFill", 24, 24, {}],
	["evenOdd", 24, 24, {}],
	["strokeRound", 32, 32, {}],
	["offsetViewBox", 48, 48, {}],
	["lucideSearch", 24, 24, { currentColor: [255, 0, 0] }],
	["mixedCurrentColor", 24, 24, {}],
	["mixedCurrentColor", 24, 24, { currentColor: [0, 128, 255] }],
	// preserveAspectRatio: same geometry, three fitting policies, non-square
	// target so the policies actually diverge.
	["aspectMeet", 100, 100, {}],
	["aspectNone", 100, 100, {}],
	["aspectSlice", 100, 100, {}],
];

const compiledByName = new Map();
for (const [name, relativePath] of FIXTURES) {
	compiledByName.set(name, compileSvgFile(join(fixturesDir, relativePath)));
}

const goldenLines = [
	"--!nocheck",
	"-- Generated by bundle.mjs: reference (Rust) raster output per fixture.",
	"return {",
];
for (const [name, width, height, options] of GOLDENS) {
	const compiled = compiledByName.get(name);
	const image = renderSvgIr(compiled.data, width, height, options);
	const colour = options.currentColor;
	goldenLines.push(
		"\t{",
		`\t\tfixture = ${luaString(name)},`,
		`\t\twidth = ${width},`,
		`\t\theight = ${height},`,
		`\t\talphaMask = ${options.alphaMask === true},`,
		colour !== undefined
			? `\t\tcurrentColor = { r = ${colour[0]}, g = ${colour[1]}, b = ${colour[2]} },`
			: "\t\tcurrentColor = nil,",
		options.strokeWidth !== undefined ? `\t\tstrokeWidth = ${options.strokeWidth},` : "",
		`\t\tabsoluteStrokeWidth = ${options.absoluteStrokeWidth === true},`,
		`\t\tpixels = ${luaString(image.pixels.toString("base64"))},`,
		"\t},",
	);
}
goldenLines.push("}", "");
writeFileSync(join(here, "goldens.luau"), goldenLines.join("\n"));

process.stdout.write(
	`bundled ${sourceFiles.length} module(s), ${FIXTURES.length} fixture(s), ` +
		`${GOLDENS.length} golden raster(s) and @rbxts/vide ${videVersion} ` +
		`(${videFiles.length} module(s))\n`,
);
